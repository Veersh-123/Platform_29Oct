/**
 * Save generated test plan file to disk
 */
export function saveTestPlanFile(
  content: string,
  storyId: string,
  outputDir: string = '../specs'
): string {
  const logger = createLogger('ai-agent-service');

  try {
    const fullOutputDir = path.join(__dirname, outputDir);
    if (!fs.existsSync(fullOutputDir)) {
      fs.mkdirSync(fullOutputDir, { recursive: true });
    }

    const filename = `${storyId.toLowerCase().replace(/\s+/g, '-')}-TEST-PLAN.md`;
    const filepath = path.join(fullOutputDir, filename);

    fs.writeFileSync(filepath, content, 'utf-8');

    console.log(`✅ Test Plan saved successfully:`);
    console.log(`   ${filepath}`);
    logger.info(`✅ Test Plan saved successfully: ${filepath}`);

    return filepath;
  } catch (error) {
    console.error(`❌ Error saving test plan: ${error}`);
    logger.error(`❌ Error saving test plan: ${error}`);
    throw error;
  }
}

