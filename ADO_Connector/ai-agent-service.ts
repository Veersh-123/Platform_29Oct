/**
 * Extract feature file content from AI response
 * Removes markdown code blocks if present
 */
export function extractFeatureContent(aiResponse: string): string {
  let content = aiResponse.trim();
  content = content.replace(/^```(?:gherkin)?\n?/, '');
  content = content.replace(/\n?```$/, '');
  return content.trim();
}

/**
 * Generate test plan using AI agent
 * Supports all 5 LLM providers: Groq, OpenAI, Claude, Ollama, Copilot
 */
export async function generateTestPlanWithAI(testPlanPrompt: string): Promise<string | null> {
  const logger = createLogger('ai-agent-service');
  const config = getAIConfig();

  if (!config) {
    console.log('⏭️  Skipping automatic test plan generation');
    logger.warn('⏭️  Skipping automatic test plan generation - AI credentials not set');
    return null;
  }

  try {
    console.log(`🤖 Generating Test Plan with AI (${config.provider})...`);
    logger.info(`🤖 Generating Test Plan with AI (${config.provider})...`);

    let content: string;

    if (config.provider === 'claude') {
      content = await callClaudeAPI(testPlanPrompt, config);
    } else if (config.provider === 'openai') {
      content = await callOpenAIAPI(testPlanPrompt, config);
    } else if (config.provider === 'groq') {
      content = await callGroqAPI(testPlanPrompt, config);
    } else if (config.provider === 'ollama') {
      content = await callOllamaAPI(testPlanPrompt, config);
    } else if (config.provider === 'copilot') {
      content = await callCopilotAPI(testPlanPrompt, config);
    } else {
      throw new Error(`Unknown AI provider: ${config.provider}`);
    }

    return content;
  } catch (error) {
    console.error('❌ Test Plan Generation Error:', error instanceof Error ? error.message : error);
    logger.error(`❌ Test Plan Generation Error: ${error instanceof Error ? error.message : error}`);
    return null;
  }
}

