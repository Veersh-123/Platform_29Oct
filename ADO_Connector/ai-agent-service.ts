/**
 * AI Agent Service for generating feature files using Claude or OpenAI
 * Supports both Claude (Anthropic) and OpenAI APIs
 */

interface AIConfig {
  provider: 'claude' | 'openai' | 'groq' | 'ollama' | 'copilot';
  apiKey?: string;
  model: string;
  baseUrl?: string;
}

/**
 * Get AI configuration from environment variables
 * Supports modern LLM_PROVIDER variable with fallback to legacy AI_PROVIDER
 */
function getAIConfig(): AIConfig | null {
  // Try modern LLM_PROVIDER first
  let provider = (process.env.LLM_PROVIDER || process.env.AI_PROVIDER || '').toLowerCase();
  let apiKey = process.env.ANTHROPIC_API_KEY || process.env.OPENAI_API_KEY || process.env.GROQ_API_KEY || process.env.OLLAMA_API_KEY || process.env.AI_API_KEY;

  // Normalize provider names
  if (provider === 'anthropic') provider = 'claude';
  
  if (!provider) {
    console.warn('⚠️  LLM_PROVIDER environment variable not set');
    console.warn('   Please set this to enable automatic feature file generation:');
    console.warn('   - LLM_PROVIDER: "groq", "openai", "claude", "ollama", or "copilot"');
    console.warn('   - Credentials: GROQ_API_KEY, OPENAI_API_KEY, ANTHROPIC_API_KEY, OLLAMA_API_KEY');
    return null;
  }

  // Copilot doesn't need API key
  if (provider !== 'copilot' && !apiKey) {
    console.warn(`⚠️  API key not found for provider: ${provider}`);
    return null;
  }

  let model = '';
  switch(provider) {
    case 'claude':
      model = process.env.ANTHROPIC_MODEL || process.env.AI_MODEL || 'claude-3-5-haiku-20241022';
      break;
    case 'openai':
      model = process.env.OPENAI_MODEL || process.env.AI_MODEL || 'gpt-4o';
      break;
    case 'groq':
      model = process.env.GROQ_MODEL || 'openai/gpt-oss-120b';
      break;
    case 'ollama':
      model = process.env.OLLAMA_MODEL || 'gpt-oss:120b';
      break;
    case 'copilot':
      model = process.env.COPILOT_MODEL || 'claude-3-5-haiku-20241022';
      break;
    default:
      model = 'claude-3-5-haiku-20241022';
  }

  return {
    provider: provider as any,
    apiKey: provider === 'copilot' ? undefined : apiKey,
    model,
    baseUrl: provider === 'ollama' ? process.env.OLLAMA_BASE_URL : undefined
  };
}

/**
 * Call Claude API to generate feature file
 */
async function callClaudeAPI(prompt: string, config: AIConfig): Promise<string> {
  return new Promise((resolve, reject) => {
    const data = JSON.stringify({
      model: config.model,
      max_tokens: 4096,
      messages: [
        {
          role: 'user',
          content: prompt
        }
      ]
    });

    const options = {
      hostname: 'api.anthropic.com',
      path: '/v1/messages',
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Content-Length': Buffer.byteLength(data),
        'x-api-key': config.apiKey,
        'anthropic-version': '2023-06-01'
      }
    };

    const req = https.request(options, (res) => {
      let responseData = '';

      res.on('data', chunk => {
        responseData += chunk;
      });

      res.on('end', () => {
        try {
          if (res.statusCode === 200) {
            const response = JSON.parse(responseData);
            const content = response.content?.[0]?.text || '';
            console.log('✅ Feature file generated by Claude');
            resolve(content);
          } else {
            const errorMsg = JSON.parse(responseData).error?.message || 'Unknown error';
            reject(new Error(`Claude API error: ${res.statusCode} - ${errorMsg}`));
          }
        } catch (e) {
          reject(new Error(`Failed to parse Claude response: ${e}`));
        }
      });
    });

    req.on('error', reject);
    req.write(data);
    req.end();
  });
}

